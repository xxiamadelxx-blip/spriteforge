function availableInputSchema(skill, providers) {
  if (skill.id === 'settings.device_info.read' || skill.id === 'files.downloads.apks.read') {
    return EMPTY_INPUT;
  }
  if (skill.id === 'yandex_pro.planned_slot_orders.read') {
    return {
      type: 'object', properties: { date: { type: 'string', enum: ['today'] } },
      additionalProperties: false,
    };
  }
  if (skill.id === 'browser.admin.run_plan') {
    return {
      type: 'object', required: ['steps'],
      properties: { domain: { type: 'string' }, steps: PLAN_STEPS },
      additionalProperties: true,
    };
  }
  const keys = providers.map((entry) => entry.id);
  return {
    type: 'object', required: ['steps'],
    anyOf: [{ required: ['provider'] }, { required: ['package'] }],
    properties: {
      provider: { type: 'string', enum: keys },
      package: { type: 'string', enum: [...skill.packages] },
      steps: PLAN_STEPS,
    },
    additionalProperties: true,
  };
}

function availabilityFor(packageName, inventory) {
  if (!inventory) return 'unknown';
  if (inventory.packages.has(packageName)) return 'available';
  return inventory.complete ? 'unavailable' : 'unknown';
}

// app.list is generated by AndroidToolExecutor.listApps. Validate its versioned
// JSON-RPC envelope and refuse to classify absent packages unless complete.
export function parseAppInventory(remote) {
  if (!remote || remote.status < 200 || remote.status >= 300) return null;
  try {
    const envelope = JSON.parse(remote.body);
    if (envelope?.error || envelope?.result?.isError === true) return null;
    const data = envelope?.result?.structuredContent;
    if (data?.status !== 'OK' || !Array.isArray(data.apps) || typeof data.truncated !== 'boolean') return null;
    if (!Number.isInteger(data.count) || data.count < data.apps.length) return null;
    if (data.apps.some((app) => typeof app?.package !== 'string' || !app.package.trim())) return null;
    const complete = !data.truncated && data.count === data.apps.length;
    return {
      packages: new Set(data.apps.map((app) => app.package)),
      complete,
      source: complete ? 'android_app_list' : 'android_app_list_truncated',
    };
  } catch {
    return null;
  }
}

export function describeApprovedSkills(inventory = null) {
  return createDefaultSkillRegistry().list().map((skill) => {
    const allowed = new Set(skill.packages || []);
    const providers = Object.entries(PROVIDERS[skill.id] || {})
      .filter(([, packageName]) => allowed.has(packageName))
      .map(([id, packageName]) => ({
        id, package: packageName, availability: availabilityFor(packageName, inventory),
      }));
    const availability = providers.some((p) => p.availability === 'available')
      ? 'available'
      : providers.length > 0 && providers.every((p) => p.availability === 'unavailable')
        ? 'unavailable'
        : 'unknown';
    return {
      id: skill.id,
      purpose: PURPOSES[skill.id] || 'Registered bounded Android skill.',
      version: Number.isInteger(skill.version) ? skill.version : null,
      packages: [...allowed],
      providers,
      input_schema: availableInputSchema(skill, providers),
      input_schema_status: 'public_subset_runtime_guards_apply',
      availability,
      effect: typeof skill.safety?.effect === 'string' ? skill.safety.effect : 'unspecified',
      risk: typeof skill.safety?.risk === 'string' ? skill.safety.risk : 'unspecified',
      oauth_scope: 'android.control',
      requires_user_takeover: true,
      takeover_condition: 'only_if_protected_authorization_or_permission_surface_is_encountered',
    };
  });
}
